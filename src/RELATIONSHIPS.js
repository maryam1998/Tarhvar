export function findAttractionsForSchema(schemaId) {
  return ATTRACTION_PATTERNS.filter((p) => p.schemas.includes(schemaId));
}

export function getResponseGuide(schemaId) {
  return HOW_TO_RESPOND[schemaId] || null;
}

export function findPattern(schemaA, schemaB) {
  return ATTRACTION_PATTERNS.find(
    (p) =>
      (p.schemas[0] === schemaA && p.schemas[1] === schemaB) ||
      (p.schemas[0] === schemaB && p.schemas[1] === schemaA)
  ) || null;
}
