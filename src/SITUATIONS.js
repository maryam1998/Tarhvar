export function getSituationsByCategory(categoryId) {
  if (!categoryId || categoryId === "all") return SITUATIONS;
  return SITUATIONS.filter((s) => s.category === categoryId);
}

export function getSituation(id) {
  return SITUATIONS.find((s) => s.id === id) || null;
}

export function getSchemasForSituation(situationId, schemas) {
  const sit = getSituation(situationId);
  if (!sit) return [];
  return sit.schemas.map((id) => {
    const s = schemas.find((x) => x.id === id);
    return s ? { id: s.id, name: s.name_plain || s.name_fa } : { id, name: id };
  });
}
