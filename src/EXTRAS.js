export function getRandomDailyPrompt(seed) {
  if (typeof seed === "number") {
    return DAILY_PROMPTS[seed % DAILY_PROMPTS.length];
  }
  return DAILY_PROMPTS[Math.floor(Math.random() * DAILY_PROMPTS.length)];
}

export function getTodayPrompt() {
  const day = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  return DAILY_PROMPTS[day % DAILY_PROMPTS.length];
}
